import json
from pathlib import Path


def load_metrics(path: str = "outputs/smoke_metrics.jsonl") -> list[dict]:
    p = Path(path)
    if not p.exists():
        return []
    rows = []
    for line in p.read_text(encoding="utf-8").splitlines():
        if line.strip():
            rows.append(json.loads(line))
    return rows
